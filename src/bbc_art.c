bool bbc_font_pixel(unsigned char ch, int col, int row)
{
    if (col < 0 || col >= BBC_FONT_CELL || row < 0 || row >= BBC_FONT_CELL)
        return false;
    if (ch < BBC_FONT_FIRST || ch > BBC_FONT_LAST)
        return true; /* the block a missing glyph printed as */
    return FONT[ch - BBC_FONT_FIRST][row * BBC_FONT_CELL + col] == '#';
}
