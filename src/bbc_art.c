const unsigned char BBC_RGB[BBC_COLOUR_COUNT][3] = {
    {0, 0, 0},       /* black */
    {255, 0, 0},     /* red */
    {0, 255, 0},     /* green */
    {255, 255, 0},   /* yellow */
    {0, 0, 255},     /* blue */
    {255, 0, 255},   /* magenta */
    {0, 255, 255},   /* cyan */
    {255, 255, 255}, /* white */
};

BbcColour bbc_colour_from_rgb(unsigned char r, unsigned char g,
                              unsigned char b)
{
    return (BbcColour)((r >= 128 ? 1 : 0) | (g >= 128 ? 2 : 0) |
                       (b >= 128 ? 4 : 0));
}

BbcColour bbc_complement(BbcColour c)
{
    return (BbcColour)((unsigned)c ^ 7u);
}

int bbc_sprite_w(const BbcSprite *sprite)
{
    if (sprite == NULL || sprite->h < 1 || sprite->rows[0] == NULL)
        return 0;
    return (int)strlen(sprite->rows[0]);
}

int bbc_sprite_code(char c)
{
    switch (c)
    {
    case '.':
        return BBC_CODE_TRANSPARENT;
    case 'K':
        return BBC_BLACK;
    case 'R':
        return BBC_RED;
    case 'G':
        return BBC_GREEN;
    case 'Y':
        return BBC_YELLOW;
    case 'B':
        return BBC_BLUE;
    case 'M':
        return BBC_MAGENTA;
    case 'C':
        return BBC_CYAN;
    case 'W':
        return BBC_WHITE;
    case '1':
    case '2':
    case '3':
    case '4':
        return BBC_CODE_SLOT0 + (c - '1');
    default:
        return BBC_CODE_INVALID;
    }
}

bool bbc_sprite_valid(const BbcSprite *sprite)
{
    if (sprite == NULL || sprite->rows == NULL || sprite->h < 1)
        return false;
    int w = bbc_sprite_w(sprite);
    if (w < 1)
        return false;
    for (int y = 0; y < sprite->h; ++y)
    {
        const char *row = sprite->rows[y];
        if (row == NULL || (int)strlen(row) != w)
            return false;
        for (int x = 0; x < w; ++x)
            if (bbc_sprite_code(row[x]) == BBC_CODE_INVALID)
                return false;
    }
    return true;
}

